function buildTreeNode(node, depth, query) {
  if (!nodeMatchesSearch(node)) {
    return null;
  }

  const listItem = document.createElement("li");
  const hasChildren = Boolean(node.children?.length);
  const isForcedOpen = Boolean(query && hasChildren);
  const isExpanded = hasChildren && (isForcedOpen || state.expandedIds.has(node.id));

  listItem.className = `tree-node depth-${depth}${isExpanded ? " is-expanded" : ""}`;

  const row = document.createElement("div");
  row.className = "tree-row";

  const selectButton = document.createElement("button");
  selectButton.className = "tree-select";
  selectButton.type = "button";
  selectButton.dataset.nodeId = node.id;
  selectButton.style.setProperty("--indent", `${21 + depth * 22}px`);
  selectButton.setAttribute("aria-current", node.id === state.selectedId ? "page" : "false");

  const dot = document.createElement("span");
  dot.className = `node-dot${isExpanded ? " is-open" : ""}`;
  dot.setAttribute("aria-hidden", "true");

  const label = document.createElement("span");
  label.className = "tree-label";
  label.textContent = node.name;

  selectButton.append(dot, label);
  row.append(selectButton);

  if (hasChildren) {
    const toggleButton = document.createElement("button");
    toggleButton.className = "tree-toggle";
    toggleButton.type = "button";
    toggleButton.dataset.toggleId = node.id;
    toggleButton.setAttribute("aria-expanded", String(isExpanded));
    toggleButton.setAttribute("aria-label", `${isExpanded ? "Свернуть" : "Развернуть"} папку «${node.name}»`);
    toggleButton.append(createIcon("icon-chevron"));
    row.append(toggleButton);
  }

  listItem.append(row);

  if (hasChildren) {
    const childrenList = document.createElement("ul");
    childrenList.className = "tree-children";

    node.children.forEach((child) => {
      const childNode = buildTreeNode(child, depth + 1, query);
      if (childNode) {
        childrenList.append(childNode);
      }
    });

    listItem.append(childrenList);
  }

  return listItem;
}

function renderTree() {
  const hasSearch = Boolean(state.searchQuery);
  const fragment = document.createDocumentFragment();
  let visibleGroups = 0;

  catalogGroups.forEach((group) => {
    const groupNode = buildTreeNode(group, 0, hasSearch);
    if (groupNode) {
      visibleGroups += 1;
      fragment.append(groupNode);
    }
  });

  treeElement.replaceChildren(fragment);
  treeEmptyElement.hidden = visibleGroups !== 0;
  clearSearchButton.hidden = searchElement.value.trim().length === 0;
}

